// Execute actual /s/:token/ auth and proxy handler source with an in-memory
// upstream. This does not claim a live HTTP/VPS or true network-proxy test.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { requireExactCachePrivacyFlag } from '../tools/cache-privacy-flags.mjs';

const requireNoStore = requireExactCachePrivacyFlag(process.argv.slice(2));

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'zbrowse/gateway/server.js'), 'utf8');
function section(startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start);
  assert.ok(start >= 0 && end > start,
    'actual gateway viewer middleware must remain extractable for QA');
  return source.slice(start, end);
}

const sessionLookup = section('function findSession(req) {', 'app.get("/api/health"');
const auth = section('app.use("/s/", (req, res, next) => {', 'const browserProxy = createProxyServer();');
const proxy = section('const browserProxy = createProxyServer();', 'app.use("/api",');

const token = 'B'.repeat(32); // synthetic token never generated by gateway
const ip = '192.0.2.8'; // RFC 5737 documentation range
const session = {
  token, ip, password: 'local-fixture-only',
  containerName: 'fixture-browser', expiresAt: Date.now() + 30_000,
  lastSeenAt: Date.now()
};
const sessions = new Map([[token, session]]);
const routes = [];
let proxied = 0;
let upstreamResponseHandler;
const sandbox = {
  app: {
    use(prefix, middleware) {
      assert.equal(prefix, '/s/', 'only authorized viewer handlers must be tested');
      routes.push(middleware);
    }
  },
  sessions,
  requestPath: (req, current) => current || req.url,
  requestIp: () => ip,
  trustProxyHops: 0,
  config: { idleMs: 300_000 },
  isSessionExpired: () => false,
  console: { error() { throw new Error('unexpected fixture proxy failure'); } },
  createProxyServer() {
    return {
      on(name, handler) {
        if (name === 'proxyRes') upstreamResponseHandler = handler;
      },
      async web(req, res, options) {
        proxied += 1;
        assert.equal(options.target, 'https://fixture-browser:3001',
          'proxy must route only to the synthetic authorized browser');
        const upstream = {
          headers: {
            'cache-control': 'public, max-age=3600',
            'content-type': 'text/html; charset=utf-8'
          }
        };
        if (upstreamResponseHandler) upstreamResponseHandler(upstream, req, res);
        res.writeHead(200, upstream.headers);
        res.end('fixture content');
      }
    };
  }
};
vm.runInNewContext(sessionLookup + '\n' + auth + '\n' + proxy, sandbox, {
  filename: 'zbrowse/gateway/server.js', timeout: 1000
});
assert.equal(routes.length, 2,
  'real gateway must have separate viewer auth and proxy forwarding routes');

function responseCapture() {
  const headers = new Map();
  return {
    statusCode: 200,
    ended: false,
    setHeader(name, value) { headers.set(name.toLowerCase(), String(value)); return this; },
    getHeader(name) { return headers.get(name.toLowerCase()); },
    set(name, value) { return this.setHeader(name, value); },
    status(code) { this.statusCode = code; return this; },
    send(body) { this.body = body; this.ended = true; return this; },
    writeHead(code, incoming = {}) {
      this.statusCode = code;
      for (const [name, value] of Object.entries(incoming)) this.setHeader(name, value);
      return this;
    },
    end(body) { this.body = body; this.ended = true; return this; }
  };
}
async function requestViewer(url) {
  const req = { url };
  const res = responseCapture();
  let authorized = false;
  routes[0](req, res, () => { authorized = true; });
  if (authorized) await routes[1](req, res);
  return { res, authorized };
}

const authorized = await requestViewer('/s/' + token + '/');
assert.equal(authorized.authorized, true, 'valid token and client IP must be authorized');
assert.equal(authorized.res.statusCode, 200, 'authorized proxy fixture must render HTTP 200');
assert.equal(authorized.res.ended, true, 'authorized proxy fixture must end the response');
assert.equal(proxied, 1, 'authorized viewer must call the actual proxy forwarding path');

const denied = await requestViewer('/s/' + 'C'.repeat(32) + '/');
assert.equal(denied.authorized, false, 'unknown viewer tokens must be forbidden');
assert.equal(denied.res.statusCode, 403, 'unknown viewer token must receive 403');
assert.equal(proxied, 1, 'unauthorized viewer must not reach upstream');

if (requireNoStore) {
  // Simulate a hostile/misconfigured upstream attempting to enable public
  // caching. The gateway must override it before serving bearer content.
  const cacheHeader = String(authorized.res.getHeader('Cache-Control') || '').toLowerCase();
  const directives = cacheHeader.split(',').map((part) => part.trim());
  assert.ok(directives.includes('no-store'),
    'authenticated viewer proxy forwarded cacheable upstream content (issue #284)');
  assert.ok(!directives.includes('public'),
    'authenticated viewer response must not retain upstream public cache policy');
  console.log('Authenticated viewer proxy no-store boundary passed');
} else {
  console.log('Actual gateway viewer authorization and proxy handler contract passed; ' +
    'strict upstream cache-privacy proof requires --require-no-store');
}
